"""Generate/check the static public methods catalog from an installed checkout.

Run: python docs/methods/generate_catalog.py [--check]
No SCF or correlated calculation is performed.
"""
import argparse
import inspect
from pathlib import Path

import ccpy.methods as api


GROUPS = {
    "mbpt": "Moller-Plesset perturbation theory",
    "cc": "Ground-state coupled cluster",
    "eomcc": "Equation-of-motion methods",
    "adc": "Algebraic-diagrammatic construction",
    "steomcc": "STEOM-CCSD",
    "steomccsdt": "Extended STEOM",
    "corrections": "Noniterative and adaptive corrections",
    "left": "Left ground and excited states",
    "lrcc": "Linear response",
    "hbar": "Similarity-transformed Hamiltonians",
    "reference": "References and materialization warnings",
    "hamiltonian": "Factorized Hamiltonian",
    "fno": "FNO policies, evaluations and preparation",
    "base": "Shared method protocol",
}


def signature(function):
    sig = inspect.signature(function)
    return str(sig.replace(parameters=[p for p in sig.parameters.values() if p.name != "self"]))


def scalar(value):
    if inspect.isclass(value):
        return value.__name__
    return repr(value)


def render():
    lines = ["Complete methods API catalog", "============================", "",
             ".. This file is generated by generate_catalog.py; edit that script or the source API.", "",
             "Every class exported by ``ccpy.methods.__all__`` is included below. Constructors",
             "are read from ``__init__`` (including inherited constructors), rather than the",
             "generic allocation signature. Defaults are class-level values; instance settings",
             "can override them. Base classes are extension protocols, not runnable methods.", "",
             "For usage and compatible scientific chains, see :doc:`ground`, :doc:`excited`,",
             ":doc:`guesses`, :doc:`spaces` and :doc:`properties`. A listed flag or inherited",
             "attribute is not a guarantee that every model/reference combination is implemented.", ""]
    names = sorted(name for name in api.__all__ if inspect.isclass(getattr(api, name)))
    unknown = {getattr(api, name).__module__ for name in names} - {"ccpy.methods." + name for name in GROUPS}
    if unknown:
        raise ValueError(f"Add catalog groups for exported modules: {sorted(unknown)}")
    for module, title in GROUPS.items():
        members = [name for name in names if getattr(api, name).__module__ == "ccpy.methods." + module]
        if not members:
            continue
        lines += [title, "-" * len(title), ""]
        for name in members:
            cls = getattr(api, name)
            lines += [".. _methods-class-" + name.lower() + ":", "", name, "~" * len(name), "",
                      ".. code-block:: text", "", "   " + name + signature(cls.__init__), ""]
            doc = cls.__dict__.get("__doc__")
            if doc:
                paragraph = inspect.cleandoc(doc).split("\n\n")[0]
                # A literal summary preserves source spelling without interpreting markup.
                lines += ["Source description::", ""] + ["   " + line for line in paragraph.splitlines()] + [""]
            lines += ["* Defined in ``" + cls.__module__ + "``."]
            if name.endswith("Base") or name == "MethodBase":
                lines += ["* Extension base; choose a concrete subclass for calculations."]
            if hasattr(cls, "requires_df_port"):
                lines += ["* Class-level ``requires_df_port = " + repr(cls.requires_df_port) + "``."]
            for attr in ("cc_class", "hbar_class", "left_class", "order", "num_particles", "num_holes",
                         "fno_sector", "default_guess", "guess_methods", "guess_multiplicity", "denominators",
                         "variants", "default_variant", "supports_stochastic", "gradient_variants",
                         "gradient_module", "gradient_function", "module", "function"):
                if hasattr(cls, attr) and getattr(cls, attr) is not None:
                    lines += ["* ``" + attr + " = " + scalar(getattr(cls, attr)) + "``."]
            public = []
            for attr, value in cls.__dict__.items():
                if attr.startswith("_"):
                    continue
                if isinstance(value, property):
                    public.append("``" + attr + "`` (property)")
                elif inspect.isfunction(value):
                    public.append("``" + attr + signature(value) + "``")
            if public:
                lines += ["* Public members defined here: " + ", ".join(public) + "."]
            lines += [""]
    lines += ["Preparation and registry functions", "----------------------------------", ""]
    for name in ("prepare_fno", "register_fno_provider", "methods_requiring_df_port"):
        function = getattr(api, name)
        lines += [name, "~" * len(name), "", ".. code-block:: text", "",
                  "   " + name + signature(function), ""]
        doc = inspect.getdoc(function)
        if doc:
            lines += ["Source description::", ""] + ["   " + line for line in doc.splitlines()] + [""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = Path(__file__).with_name("catalog.rst")
    text = render()
    if args.check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit("Methods catalog is stale; run docs/methods/generate_catalog.py")
        print("Methods catalog matches the installed API.")
    else:
        path.write_text(text)
        print(f"Wrote {path}")


if __name__ == "__main__":
    main()
