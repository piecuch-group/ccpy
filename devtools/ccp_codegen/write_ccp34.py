"""Write ccpy/lib/fortran/ccp34_adaptive_loops.f90 (generated from the crcc24X_ijkl kernels of
crcc24_opt_loops.f90: P-space skip and selection buffer added; CIM central-selection copies of the
RHF kernels).

usage: python write_ccp34.py
"""
import re
from pathlib import Path

FORTRAN = Path(__file__).resolve().parents[2] / "ccpy" / "lib" / "fortran"
src = (FORTRAN / "crcc24_opt_loops.f90").read_text().splitlines()

# virtual loop order of each kernel (matches the t4_excitations columns) and the
# spinorbital encoding (odd = alpha, even = beta) of (v1, v2, v3, v4, o1, o2, o3, o4)
KERNELS = {
    "A": ("a,b,c,d", "2*a-1,2*b-1,2*c-1,2*d-1,2*i-1,2*j-1,2*k-1,2*l-1"),
    "B": ("a,b,c,d", "2*a-1,2*b-1,2*c-1,2*d,2*i-1,2*j-1,2*k-1,2*l"),
    "C": ("a,b,c,d", "2*a-1,2*b-1,2*c,2*d,2*i-1,2*j-1,2*k,2*l"),
    "D": ("d,a,b,c", "2*d-1,2*a,2*b,2*c,2*l-1,2*i,2*j,2*k"),
    "E": ("a,b,c,d", "2*a,2*b,2*c,2*d,2*i,2*j,2*k,2*l"),
}

DECL = """                        real(kind=8), intent(inout) :: moments(buf_fact*num_add)
                        !f2py intent(in,out) :: moments(0:buf_fact*num_add-1)
                        integer, intent(inout) :: quads_list(buf_fact*num_add,8)
                        !f2py intent(in,out) :: quads_list(0:buf_fact*num_add-1,0:7)
                        integer, intent(inout) :: nfill
                        !f2py intent(in,out) :: nfill
                        real(kind=8), intent(inout) :: cutoff
                        !f2py intent(in,out) :: cutoff
                        integer, intent(in) :: num_add, buf_fact, n4p
                        real(kind=8), intent(in) :: min_thresh
                        integer(kind=8), intent(in) :: pkeys(n4p)
{rhf}
                        integer :: ip
                        real(kind=8) :: val"""


def key(vs):
    v = vs.split(",")
    return f"quad_key({v[0]},{v[1]},{v[2]},{v[3]})"


out = ["module ccp34_adaptive_loops",
       "  ! CC(P;4) quadruples correction (two-body approximation, CR-CC(2,4) moments) for adaptive",
       "  ! CC(P;Q) with selection. Each ccp4X_ijkl_with_selection routine is the crcc24X_ijkl kernel",
       "  ! of crcc24_opt_loops for one occupied block (i,j,k,l), restricted to the quadruples outside",
       "  ! the P space and appending those of largest |moment contribution| to the selection buffer.",
       "  ! The P space of the block is given as the sorted keys quad_key(v1,v2,v3,v4) of its",
       "  ! virtual indices (columns 1-4 of t4_excitations), terminated by a key larger than any other.",
       "  ! Generated by devtools/ccp_codegen/write_ccp34.py; the moments are built by ccpy.moments.crcc24.",
       "  use pspace_sort, only: keep_largest",
       "",
       "    implicit none",
       "",
       "            contains",
       "",
       "              pure integer(kind=8) function quad_key(v1, v2, v3, v4)",
       "              ! 15 bits per index (shortcut: at most 32767 virtual orbitals per spin)",
       "                        integer, intent(in) :: v1, v2, v3, v4",
       "                        quad_key = ior(ishft(int(v1,8),45), ior(ishft(int(v2,8),30), ior(ishft(int(v3,8),15), int(v4,8))))",
       "              end function quad_key",
       "",
       "              subroutine push_quadruple(moments, quads_list, nfill, cutoff, num_add, buf_fact, val, q)",
       "              ! Append one quadruple to the selection buffer. When the buffer is full, only its num_add",
       "              ! largest entries are kept and cutoff is raised to the smallest of them (as add_candidates",
       "              ! of ccp3_adaptive_loops).",
       "                        integer, intent(in) :: num_add, buf_fact",
       "                        real(kind=8), intent(inout) :: moments(buf_fact*num_add)",
       "                        integer, intent(inout) :: quads_list(buf_fact*num_add,8)",
       "                        integer, intent(inout) :: nfill",
       "                        real(kind=8), intent(inout) :: cutoff",
       "                        real(kind=8), intent(in) :: val",
       "                        integer, intent(in) :: q(8)",
       "                        integer :: nbuf, imin",
       "",
       "                        nbuf = buf_fact*num_add",
       "                        if (num_add <= 0) return",
       "                        if (nfill > nbuf) then",
       "                           if (nbuf > num_add) then",
       "                              call keep_largest(moments, quads_list, nbuf, num_add, cutoff)",
       "                              nfill = num_add + 1",
       "                              if (abs(val) < cutoff) return",
       "                           else",
       "                              ! buffer of exactly num_add entries: replace the smallest one",
       "                              imin = minloc(abs(moments), 1)",
       "                              if (abs(val) > abs(moments(imin))) then",
       "                                 moments(imin) = val",
       "                                 quads_list(imin,:) = q",
       "                              end if",
       "                              cutoff = minval(abs(moments))",
       "                              return",
       "                           end if",
       "                        end if",
       "                        moments(nfill) = val",
       "                        quads_list(nfill,:) = q",
       "                        nfill = nfill + 1",
       "              end subroutine push_quadruple",
       ""]

CENTRAL_HEADER = [
    "              ! CIM (closed-shell RHF): copies of the aaaa, aaab, and aabb kernels above that rank each",
    "              ! Q-space quadruple by its contribution to the central (CIM-projected) energy,",
    "              ! l (P_1 + P_2 + P_3 + P_4) M / (4 D), from the central moment dx4 = (P_1 + ... + P_4) x4",
    "              ! supplied by the caller, and also return the sum of these contributions",
    "              ! (deltaD_central); the other corrections are the subsystem's full ones.",
]

for central in (False, True):
    if central:
        out.extend(CENTRAL_HEADER)
    for name, (loop, enc) in KERNELS.items():
        if central and name in ("D", "E"):
            continue
        suffix = "_with_central_selection" if central else "_with_selection"
        x4 = "x4" + name.lower()
        start = next(n for n, l in enumerate(src) if re.match(rf"\s*subroutine crcc24{name}_ijkl\(", l))
        end = next(n for n, l in enumerate(src) if re.match(rf"\s*end subroutine crcc24{name}_ijkl", l))
        body = src[start:end + 1]
        new = []
        nloop = 0
        header_done = decl_done = False
        mm24 = None  # lines of the antisymmetrization of x4 while it is being read
        for line in body:
            if re.match(rf"\s*subroutine crcc24{name}_ijkl\(", line):
                line = line.replace(f"crcc24{name}_ijkl", f"ccp4{name}_ijkl{suffix}")
                new.append(line.replace("deltaD,&", "deltaD,deltaD_central,&") if central else line)
                new.append("                              moments,quads_list,nfill,cutoff,&")
                continue
            if central and re.match(rf"\s*{x4},", line):
                new.append(line.replace(f"{x4},", f"{x4},d{x4},", 1))
                continue
            if central and re.match(rf"\s*real\(kind=8\), intent\(in\) :: {x4}\(", line):
                new.append(line)
                new.append(line.replace(f":: {x4}(", f":: d{x4}("))
                continue
            if not header_done and re.match(r"\s*no[ab],nu[ab].*\)\s*$", line):
                new.append("                              pkeys,num_add,min_thresh,buf_fact," + ("rhf," if name == "C" else "") + "&")
                new.append(line.replace(")", ",n4p)"))
                header_done = True
                continue
            if not decl_done and re.match(r"\s*integer :: a, b, c, d\s*$", line):
                new.append(line)
                rhf = ("                        logical, intent(in) :: rhf  ! push only aabb quadruples not after their\n"
                       "                        ! spin flip (c,d,a,b,k,l,i,j); the selection adds both") if name == "C" else ""
                new.extend(DECL.format(rhf=rhf).splitlines() if rhf else
                           [x for x in DECL.format(rhf="").splitlines() if x.strip()])
                if central:
                    new.append("                        real(kind=8), intent(out) :: deltaD_central")
                    new.append("                        real(kind=8) :: dmm24, rank")
                decl_done = True
                continue
            if central and re.match(r"\s*deltaD = 0\.0d0\s*$", line):
                new.append(line)
                new.append(line.replace("deltaD = 0.0d0", "deltaD_central = 0.0d0"))
                continue
            if re.match(r"\s*end subroutine", line):
                new.append(line.replace(f"crcc24{name}_ijkl", f"ccp4{name}_ijkl{suffix}"))
                continue
            if re.match(r"\s*do [abcd] = ", line):
                indent = re.match(r"(\s*)", line).group(1)
                if nloop == 0:
                    new.append(indent + "ip = 1")
                new.append(line)
                nloop += 1
                if nloop == 4:
                    ind = indent + "    "
                    new.append(ind + "! skip the quadruples of the P space (pkeys and the loops are both in ascending key order)")
                    new.append(ind + f"do while (pkeys(ip) < {key(loop)})")
                    new.append(ind + "    ip = ip + 1")
                    new.append(ind + "end do")
                    new.append(ind + f"if (pkeys(ip) == {key(loop)}) cycle")
                    new.append("")
                continue
            if central and (mm24 is not None or re.match(r"\s*mm24 = ", line)):
                mm24 = (mm24 or []) + [line]
                new.append(line)
                if not line.rstrip().endswith("&"):
                    new.append("")
                    new.extend(re.sub(rf"\b{x4}\(", f"d{x4}(", l).replace("mm24 =", "dmm24 =", 1) for l in mm24)
                    mm24 = None
                continue
            new.append(line)
            if re.match(r"\s*deltaD = deltaD \+ temp/denom", line):
                ind = re.match(r"(\s*)", line).group(1)
                val = "rank" if central else "val"
                cond = f"abs({val}) > min_thresh .and. abs({val}) >= cutoff"
                if name == "C":
                    cond += " .and. .not. (rhf .and. quad_key(c,d,k,l) < quad_key(a,b,i,j))"
                new.append("")
                if central:
                    new.append(ind + "! central part of the contribution, the CIM ranking quantity")
                    new.append(ind + "rank = dmm24*l4/(4.0d0*denom)")
                    new.append(ind + "deltaD_central = deltaD_central + rank")
                else:
                    new.append(ind + "val = temp/denom")
                new.append(ind + f"if ({cond}) then")
                new.append(ind + f"    call push_quadruple(moments, quads_list, nfill, cutoff, num_add, buf_fact, {val},&")
                new.append(ind + f"                        (/{enc}/))")
                new.append(ind + "end if")
        assert header_done and decl_done and nloop == 4, name
        out.extend(new)
        out.append("")

out.append("end module ccp34_adaptive_loops")
(FORTRAN / "ccp34_adaptive_loops.f90").write_text("\n".join(out) + "\n")
