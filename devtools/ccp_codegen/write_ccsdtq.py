"""Write ccpy/lib/fortran/ccsdtq_p_loops.f90 (generated from ccsdt_p_loops.f90 and ccpy/cc/ccsdtq.py).

usage: python write_ccsdtq.py
"""
from pathlib import Path

from assemble import assemble

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "ccpy/lib/fortran/ccsdtq_p_loops.f90"
KERNEL_DIR = ROOT / "ccpy/lib/fortran/ccsdtq_p"   # one module per T4 kernel, e.g. ccsdtq_p/t4c_p_b2.f90
HEAD = "! GENERATED by devtools/ccp_codegen/write_ccsdtq.py from ccsdt_p_loops.f90 and ccpy/cc/ccsdtq.py -- do not edit by hand\n"

# entry points called from ccpy/cc/ccsdtq_p.py
ENTRY_POINTS = (["update_t1a", "update_t1b", "update_t2a", "update_t2b", "update_t2c"]
                + [f"update_t3{x}_p" for x in "abcd"] + ["add_vt3_p"] + [f"update_t4{x}_p" for x in "abcde"])


def main():
    src, _, kernels = assemble()
    TARGET.write_text(HEAD + src)
    print(f"wrote {TARGET} ({len(src.splitlines())} lines)")
    KERNEL_DIR.mkdir(exist_ok=True)
    for old in KERNEL_DIR.glob("*.f90"):
        old.unlink()
    for name, text in kernels.items():
        (KERNEL_DIR / f"{name}.f90").write_text(HEAD + text)
    print(f"wrote {len(kernels)} kernels to {KERNEL_DIR}")


def kernel_files():
    return sorted(KERNEL_DIR.glob("*.f90"))


if __name__ == "__main__":
    main()
